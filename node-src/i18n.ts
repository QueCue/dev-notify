let current: Locale = 'zh';

export function setLocale(locale: Locale): void { current = locale; }
export function getLocale(): Locale { return current; }

export function parseLocale(value: unknown): Locale | undefined {
  if (typeof value !== 'string') return undefined;
  const normalized = value.trim().toLowerCase();
  if (['zh', 'zh-cn', 'zh_cn'].includes(normalized)) return 'zh';
  if (['en', 'en-us', 'en_us'].includes(normalized)) return 'en';
  return undefined;
}

export function resolveLocale(explicit: unknown, env: Env, configured: unknown): Locale {
  return parseLocale(explicit) ?? parseLocale(env.DEV_NOTIFY_LANG) ?? parseLocale(configured) ?? 'zh';
}

export function localeName(locale: Locale = current): string {
  return locale === 'zh' ? '简体中文' : 'English';
}

export function joinList(items: readonly string[]): string {
  return items.join(current === 'zh' ? '、' : ', ');
}

export function t(key: MessageKey, params: Params = {}): string {
  const message = current === 'en' ? en[key] : zh[key];
  if (typeof message === 'function') return message(params);
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : match);
}
